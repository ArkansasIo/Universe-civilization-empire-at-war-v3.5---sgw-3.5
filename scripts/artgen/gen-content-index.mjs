// Rebuilds src/utils/contentImages.ts from the files in public/images/content/<collection>/<id>.webp.
// Run after adding or removing content art:  node scripts/artgen/gen-content-index.mjs
import { readdirSync, readFileSync, writeFileSync, statSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const contentDir = join(root, 'public', 'images', 'content');
const target = join(root, 'src', 'utils', 'contentImages.ts');

// Natural sort so galaxy_boss_g2 comes before galaxy_boss_g10.
const natural = (a, b) => a.localeCompare(b, 'en', { numeric: true });

const collections = readdirSync(contentDir)
  .filter((d) => statSync(join(contentDir, d)).isDirectory())
  .sort();

const lines = collections.map((c) => {
  const ids = readdirSync(join(contentDir, c))
    .filter((f) => f.endsWith('.webp'))
    .map((f) => f.slice(0, -5))
    .sort(natural);
  return `  ${c}: [${ids.map((id) => `'${id}'`).join(', ')}],`;
});

const src = readFileSync(target, 'utf8');
const start = src.indexOf('const AVAILABLE');
const end = src.indexOf('};', start) + 2;
if (start < 0 || end < 2) throw new Error('AVAILABLE block not found in contentImages.ts');

const block = `const AVAILABLE: Record<string, readonly string[]> = {\n${lines.join('\n')}\n};`;
writeFileSync(target, src.slice(0, start) + block + src.slice(end));
console.log(`contentImages.ts: ${collections.length} collections updated`);

// Per-screen header banners: public/images/ui-art/pages/<screen id>.webp -> src/utils/pageArt.ts
const pagesDir = join(root, 'public', 'images', 'ui-art', 'pages');
const pageIds = readdirSync(pagesDir)
  .filter((f) => f.endsWith('.webp'))
  .map((f) => f.slice(0, -5))
  .sort(natural);
const chunks = [];
for (let i = 0; i < pageIds.length; i += 6) chunks.push('  ' + pageIds.slice(i, i + 6).map((id) => `'${id}'`).join(', ') + ',');
writeFileSync(
  join(root, 'src', 'utils', 'pageArt.ts'),
  `// Generated by scripts/artgen/gen-content-index.mjs from public/images/ui-art/pages/<id>.webp.
// Banners are rendered by scripts/artgen/scenes.py. Regenerate after adding images; do not edit by hand.

const PAGE_ART: ReadonlySet<string> = new Set([
${chunks.join('\n')}
]);

// Header banner for one feature screen (sidebar item id), if it has its own art.
export function getPageArt(id: string | undefined): string | undefined {
  if (!id || !PAGE_ART.has(id)) return undefined;
  return \`\${import.meta.env.BASE_URL}images/ui-art/pages/\${id}.webp\`;
}
`,
);
console.log(`pageArt.ts: ${pageIds.length} screen banners`);
